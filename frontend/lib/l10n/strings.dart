import 'package:flutter/foundation.dart';

/// Supported app languages: (code, English label, native label).
const List<(String, String, String)> kSupportedLanguages = [
  ('en', 'English', 'English'),
  ('hi', 'Hindi', 'हिन्दी'),
  ('ta', 'Tamil', 'தமிழ்'),
  ('te', 'Telugu', 'తెలుగు'),
  ('ml', 'Malayalam', 'മലയാളം'),
  ('kn', 'Kannada', 'ಕನ್ನಡ'),
];

/// Holds the currently selected app language and notifies the whole app
/// on change so every screen rebuilds with the new strings.
class AppLanguage {
  AppLanguage._();

  static String current = 'en';
  static final ValueNotifier<String> notifier = ValueNotifier<String>('en');

  static String labelFor(String code) {
    for (final (c, label, _) in kSupportedLanguages) {
      if (c == code) return label;
    }
    return 'English';
  }

  static void set(String code) {
    if (!kSupportedLanguages.any((l) => l.$1 == code)) code = 'en';
    current = code;
    notifier.value = code;
  }
}

/// Translates [key] into the current language.
/// Falls back to English, then to the key itself.
String tr(String key) {
  final lang = _table[AppLanguage.current];
  if (lang != null && lang.containsKey(key)) return lang[key]!;
  final en = _table['en'];
  if (en != null && en.containsKey(key)) return en[key]!;
  return key;
}

/// Convenience: tr() with `{placeholder}` replacement.
String trf(String key, Map<String, String> values) {
  var out = tr(key);
  values.forEach((k, v) => out = out.replaceAll('{$k}', v));
  return out;
}

